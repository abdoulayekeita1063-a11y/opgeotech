/**
 * Client-side PDF export: opens a print window with clean Swiss-styled
 * markup and triggers the browser's print-to-PDF dialog.
 */
export function exportRecordAsPdf(title: string, htmlBody: string) {
  const w = window.open("", "_blank", "width=900,height=1100");
  if (!w) return;
  w.document.write(`<!doctype html>
<html>
<head>
<meta charset="utf-8" />
<title>${escapeHtml(title)}</title>
<style>
  @page { margin: 20mm; }
  * { box-sizing: border-box; }
  body {
    font-family: "Helvetica Neue", Helvetica, Arial, sans-serif;
    color: #111; margin: 0; padding: 24px; line-height: 1.55; font-size: 13px;
  }
  .pdf-header { display: flex; align-items: center; gap: 10px; border-bottom: 2px solid #111; padding-bottom: 12px; margin-bottom: 20px; }
  .pdf-square { width: 14px; height: 14px; background: #d32f2f; }
  .pdf-brand { font-weight: 800; letter-spacing: 0.05em; text-transform: uppercase; font-size: 14px; }
  .pdf-date { margin-left: auto; font-family: monospace; font-size: 11px; color: #555; }
  h1 { font-size: 22px; margin: 0 0 4px; letter-spacing: -0.02em; }
  h2 { font-size: 15px; margin: 22px 0 8px; border-bottom: 1px solid #111; padding-bottom: 4px; }
  h3 { font-size: 13px; margin: 16px 0 6px; }
  table { width: 100%; border-collapse: collapse; margin: 10px 0; font-size: 12px; }
  th, td { border: 1px solid #111; padding: 6px 8px; text-align: left; }
  th { background: #f4f4f4; text-transform: uppercase; font-size: 10px; letter-spacing: 0.08em; }
  .metric { font-family: monospace; }
  ul { padding-left: 18px; }
  .footer { margin-top: 32px; border-top: 1px solid #111; padding-top: 8px; font-size: 10px; color: #666; font-family: monospace; }
</style>
</head>
<body>
  <div class="pdf-header">
    <div class="pdf-square"></div>
    <div class="pdf-brand">OPGeotech</div>
    <div class="pdf-date">${new Date().toLocaleString()}</div>
  </div>
  ${htmlBody}
  <div class="footer">Generated by OPGeotech — Geotechnical Engineering Platform</div>
  <script>window.onload = function(){ setTimeout(function(){ window.print(); }, 300); };</script>
</body>
</html>`);
  w.document.close();
}

export function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/** Very small markdown → HTML converter for report exports */
export function markdownToHtml(md: string): string {
  const lines = md.split("\n");
  const out: string[] = [];
  let inList = false;
  let inTable = false;

  const closeList = () => {
    if (inList) {
      out.push("</ul>");
      inList = false;
    }
  };
  const closeTable = () => {
    if (inTable) {
      out.push("</table>");
      inTable = false;
    }
  };

  const inline = (s: string) =>
    escapeHtml(s)
      .replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>")
      .replace(/\*(.+?)\*/g, "<em>$1</em>")
      .replace(/`(.+?)`/g, "<code>$1</code>");

  for (const raw of lines) {
    const line = raw.trimEnd();
    if (/^\s*\|/.test(line)) {
      closeList();
      const cells = line.replace(/^\s*\|/, "").replace(/\|\s*$/, "").split("|");
      if (cells.every(c => /^\s*:?-+:?\s*$/.test(c))) continue; // separator row
      if (!inTable) {
        out.push("<table>");
        inTable = true;
        out.push("<tr>" + cells.map(c => `<th>${inline(c.trim())}</th>`).join("") + "</tr>");
      } else {
        out.push("<tr>" + cells.map(c => `<td>${inline(c.trim())}</td>`).join("") + "</tr>");
      }
      continue;
    }
    closeTable();
    if (/^#{1,6}\s/.test(line)) {
      closeList();
      const level = Math.min(3, (line.match(/^#+/) as RegExpMatchArray)[0].length);
      out.push(`<h${level}>${inline(line.replace(/^#+\s*/, ""))}</h${level}>`);
    } else if (/^\s*[-*]\s+/.test(line)) {
      if (!inList) {
        out.push("<ul>");
        inList = true;
      }
      out.push(`<li>${inline(line.replace(/^\s*[-*]\s+/, ""))}</li>`);
    } else if (line.trim() === "") {
      closeList();
    } else {
      closeList();
      out.push(`<p>${inline(line)}</p>`);
    }
  }
  closeList();
  closeTable();
  return out.join("\n");
}
